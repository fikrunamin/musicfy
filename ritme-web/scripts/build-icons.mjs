// Writes src/ui/icon-paths.ts from Material Symbols Rounded (weight 400, Apache-2.0), so icons are
// inline SVG paths: no icon font, no CDN. Run with the `rounded` folder of
// @material-symbols/svg-400@0.49.0 (see the README, "Icons"):
//   node scripts/build-icons.mjs <dir>/package/rounded
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NAMES = [
  'add',
  'album',
  'arrow_downward',
  'arrow_upward',
  'check_circle',
  'close',
  'content_copy',
  'content_paste',
  'delete',
  'dock_to_left',
  'error',
  'forward_10',
  'fullscreen',
  'fullscreen_exit',
  'group',
  'headphones',
  'info',
  'ios_share',
  'keyboard_arrow_down',
  'light_mode',
  'link',
  'lock',
  'logout',
  'more_vert',
  'movie',
  'music_note',
  'open_in_new',
  'pause',
  'person_remove',
  'play_arrow',
  'playlist_play',
  'power_settings_new',
  'queue_music',
  'radio_button_checked',
  'replay_10',
  'search',
  'settings_remote',
  'skip_next',
  'skip_previous',
  'smart_display',
  'star',
  'stop_circle',
  'sync',
  'timer',
  'update',
  'warning',
  'wifi_off',
];

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/build-icons.mjs <path to @material-symbols/svg-400/rounded>');
  process.exit(1);
}

const entries = NAMES.map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const match = /<path d="([^"]+)"\/>/.exec(svg);
  if (!match || svg.split('<path').length !== 2) throw new Error(`${name}.svg is not a single-path icon`);
  return `  ${name}: '${match[1]}',`;
});

const out = `// Generated by scripts/build-icons.mjs from @material-symbols/svg-400@0.49.0 (rounded).
// Material Symbols: Apache License 2.0, see icon-paths.LICENSE.txt. Do not edit by hand.
// viewBox "0 -960 960 960".
export const ICON_PATHS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(new URL('../src/ui/icon-paths.ts', import.meta.url), out);
console.log(`wrote ${NAMES.length} icons to src/ui/icon-paths.ts`);
